import os
import re
import glob
import json
from datetime import datetime

# Konfigurasi folder & URL GitHub Pages
RAW_DIR = "raw_modules"      # Folder berisi file mentah modul-01.html, modul-02.html, dst.
OUT_DIR = "modules"          # Folder tujuan JS untuk GitHub Pages
SITEMAP_FILE = "sitemap.xml"
BASE_URL = "https://ejenali1.github.io/fisika-developer-clone"

# Pola CDN eksternal yang sudah dimuat secara global di modul.html
REDUNDANT_SRC_PATTERNS = [
    r"three\.min\.js",
    r"three\.js",
    r"OrbitControls\.js",
    r"CSS2DRenderer\.js",
    r"CSS3DRenderer\.js",
    r"EffectComposer\.js",
    r"RenderPass\.js",
    r"ShaderPass\.js",
    r"CopyShader\.js",
    r"LuminosityHighPassShader\.js",
    r"UnrealBloomPass\.js",
    r"chart\.js",
    r"chart\.umd\.min\.js",
    r"mathjax"
]

def is_redundant_script(tag_attrs: str) -> bool:
    src_match = re.search(r'src\s*=\s*["\']([^"\']+)["\']', tag_attrs, re.IGNORECASE)
    if not src_match:
        return False
    src_url = src_match.group(1)
    return any(re.search(pat, src_url, re.IGNORECASE) for pat in REDUNDANT_SRC_PATTERNS)

def extract_html_and_scripts(raw_html: str):
    inline_scripts = []

    def script_replacer(match):
        attrs = match.group(1) or ""
        body = match.group(2) or ""
        if is_redundant_script(attrs):
            return ""  # Buang CDN duplikat
        if 'src=' in attrs.lower():
            return match.group(0)  # Pertahankan script eksternal khusus jika ada
        if body.strip():
            inline_scripts.append(body.strip())
        return ""

    clean_html = re.sub(
        r"<script([^>]*)>([\s\S]*?)</script>",
        script_replacer,
        raw_html,
        flags=re.IGNORECASE
    ).strip()

    return clean_html, inline_scripts

def build_module_js(mod_num: int, clean_html: str, inline_scripts: list) -> str:
    html_json = json.dumps(clean_html, ensure_ascii=False)
    lines = [
        f"// Auto-generated by convert_modul.py — Module #{mod_num:02d}",
        "(function() {",
        '  var mount = document.getElementById("f3d-module-mount");',
        "  if (!mount) return;",
        f"  mount.innerHTML = {html_json};",
        ""
    ]

    for idx, code in enumerate(inline_scripts, start=1):
        lines.extend([
            f"  // Inline script #{idx}",
            "  try {",
            code,
            "  } catch (err) {",
            f"    console.error('Module #{mod_num:02d} script #{idx} error:', err);",
            "    var errBox = document.createElement('div');",
            "    errBox.style.cssText = 'margin-top:10px;padding:10px;background:rgba(239,68,68,0.15);border:1px solid #ef4444;color:#fca5a5;border-radius:6px;font-size:12px;';",
            "    errBox.textContent = 'Runtime Error: ' + err.message;",
            "    mount.appendChild(errBox);",
            "  }",
            ""
        ])

    lines.append("})();")
    return "\n".join(lines)

def generate_sitemap(module_ids: list):
    today = datetime.now().strftime("%Y-%m-%d")
    urls = [
        f"  <url><loc>{BASE_URL}/index.html</loc><lastmod>{today}</lastmod><priority>1.0</priority></url>"
    ]
    for mid in sorted(set(module_ids)):
        urls.append(
            f"  <url><loc>{BASE_URL}/modul.html?id={mid}</loc><lastmod>{today}</lastmod><priority>0.8</priority></url>"
        )

    xml_content = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "\n".join(urls)
        + "\n</urlset>\n"
    )
    with open(SITEMAP_FILE, "w", encoding="utf-8") as f:
        f.write(xml_content)
    print(f"[OK] {SITEMAP_FILE} diperbarui ({len(module_ids)} modul).")

def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    converted_ids = []

    # 1. Konversi semua file HTML mentah di RAW_DIR (jika folder ada)
    if os.path.isdir(RAW_DIR):
        html_files = sorted(glob.glob(os.path.join(RAW_DIR, "*.html")))
        for path in html_files:
            num_match = re.search(r"(\d+)", os.path.basename(path))
            if not num_match:
                continue
            mod_num = int(num_match.group(1))
            with open(path, "r", encoding="utf-8", errors="replace") as f:
                raw_html = f.read()

            clean_html, scripts = extract_html_and_scripts(raw_html)
            js_output = build_module_js(mod_num, clean_html, scripts)
            out_path = os.path.join(OUT_DIR, f"modul-{mod_num:02d}.js")
            with open(out_path, "w", encoding="utf-8") as f:
                f.write(js_output)
            print(f"[CONVERTED] {os.path.basename(path)} -> {out_path}")

    # 2. Pindai seluruh modul-*.js yang ada di OUT_DIR untuk update sitemap
    for js_file in sorted(glob.glob(os.path.join(OUT_DIR, "modul-*.js"))):
        m = re.search(r"modul-(\d+)\.js$", os.path.basename(js_file))
        if m:
            converted_ids.append(int(m.group(1)))

    if converted_ids:
        generate_sitemap(converted_ids)
    else:
        print(f"[INFO] Tidak ada file di '{RAW_DIR}/' maupun '{OUT_DIR}/'.")

if __name__ == "__main__":
    main()
